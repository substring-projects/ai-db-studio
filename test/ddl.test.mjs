import test from 'node:test';
import assert from 'node:assert';
import {
  buildCreateTable,
  columnTypeSql,
  defaultExpression,
  defaultOptions,
  emptyColumn,
  enumValues,
  validateTable,
} from '../src/renderer/lib/ddl.ts';

const spec = (patch = {}) => ({
  name: 'orders',
  columns: [],
  foreignKeys: [],
  indexes: [],
  options: defaultOptions(),
  ...patch,
});

test('postgres auto-increment uses an identity column', () => {
  const sql = buildCreateTable(
    'POSTGRESQL',
    spec({ columns: [emptyColumn({ name: 'id', type: 'BIGINT', params: '', primaryKey: true, autoIncrement: true })] })
  );
  assert.equal(sql, 'CREATE TABLE "orders" (\n  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY\n);');
});

test('mysql auto-increment, unsigned, on update and options', () => {
  const sql = buildCreateTable(
    'MYSQL',
    spec({
      columns: [
        emptyColumn({ name: 'id', type: 'INT', params: '', primaryKey: true, autoIncrement: true, unsigned: true }),
        emptyColumn({ name: 'updated_at', type: 'TIMESTAMP', params: '', notNull: true, defaultValue: 'current_timestamp', onUpdateNow: true }),
        emptyColumn({ name: 'status', type: 'ENUM', params: "new, 'it''s done'", comment: 'Order state' }),
      ],
      options: { ...defaultOptions(), storageEngine: 'InnoDB', charset: 'utf8mb4', comment: 'All orders' },
    })
  );
  assert.ok(sql.includes('`id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY'));
  assert.ok(sql.includes('`updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP'));
  assert.ok(sql.includes("`status` ENUM('new', 'it''s done') COMMENT 'Order state'"));
  assert.ok(sql.endsWith("ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='All orders';"));
});

test('composite primary key, foreign keys and indexes', () => {
  const columns = [
    emptyColumn({ name: 'order_id', type: 'BIGINT', params: '', primaryKey: true }),
    emptyColumn({ name: 'product_id', type: 'BIGINT', params: '', primaryKey: true }),
    emptyColumn({ name: 'sku', type: 'VARCHAR', params: '64', comment: "SKU's code" }),
  ];
  const fk = { name: '', column: 'order_id', refTable: 'orders', refColumn: 'id', onDelete: 'CASCADE', onUpdate: 'NO ACTION' };
  const index = { name: '', columns: ['sku'], unique: true };
  const pg = buildCreateTable('POSTGRESQL', spec({ name: 'items', schema: 'shop', columns, foreignKeys: [fk], indexes: [index] }));
  assert.ok(pg.includes('  PRIMARY KEY ("order_id", "product_id")'));
  assert.ok(!pg.includes('"order_id" BIGINT NOT NULL PRIMARY KEY'));
  assert.ok(pg.includes('CONSTRAINT "fk_items_order_id" FOREIGN KEY ("order_id") REFERENCES "orders" ("id") ON DELETE CASCADE'));
  assert.ok(pg.includes('CREATE UNIQUE INDEX "uq_items_sku" ON "shop"."items" ("sku");'));
  assert.ok(pg.includes(`COMMENT ON COLUMN "shop"."items"."sku" IS 'SKU''s code';`));

  const my = buildCreateTable('MYSQL', spec({ name: 'items', columns, foreignKeys: [fk], indexes: [index] }));
  assert.ok(my.includes('UNIQUE KEY `uq_items_sku` (`sku`)'));
  assert.equal(my.split(';').length, 2, 'MySQL output is one statement');
});

test('defaults: values are quoted, expressions are kept', () => {
  assert.equal(defaultExpression('active'), "'active'");
  assert.equal(defaultExpression("it's"), "'it''s'");
  assert.equal(defaultExpression('42'), '42');
  assert.equal(defaultExpression('-1.5'), '-1.5');
  assert.equal(defaultExpression('now()'), 'now()');
  assert.equal(defaultExpression('gen_random_uuid()'), 'gen_random_uuid()');
  assert.equal(defaultExpression('true'), 'TRUE');
  assert.equal(defaultExpression("'x'"), "'x'");
  assert.equal(defaultExpression("'{}'::jsonb"), "'{}'::jsonb");
  assert.equal(defaultExpression('(1 + 2)'), '(1 + 2)');
  assert.equal(defaultExpression(''), '');
});

test('mysql wraps defaults on TEXT, BLOB and JSON columns in parentheses', () => {
  const sql = buildCreateTable(
    'MYSQL',
    spec({
      columns: [
        emptyColumn({ name: 'note', type: 'TEXT', params: '', defaultValue: 'none yet' }),
        emptyColumn({ name: 'meta', type: 'JSON', params: '', defaultValue: "('{}')" }),
        emptyColumn({ name: 'tags', type: 'json', params: '', defaultValue: 'json_array()' }),
        emptyColumn({ name: 'body', type: 'LONGTEXT', params: '', defaultValue: 'null' }),
        emptyColumn({ name: 'title', type: 'VARCHAR', params: '100', defaultValue: 'untitled' }),
      ],
    })
  );
  assert.ok(sql.includes("`note` TEXT DEFAULT ('none yet')"));
  assert.ok(sql.includes("`meta` JSON DEFAULT ('{}')"), 'already wrapped stays as is');
  assert.ok(sql.includes('`tags` json DEFAULT (json_array())'));
  assert.ok(sql.includes('`body` LONGTEXT DEFAULT NULL'), 'NULL needs no parentheses');
  assert.ok(sql.includes("`title` VARCHAR(100) DEFAULT 'untitled'"), 'other types are unchanged');

  const pg = buildCreateTable('POSTGRESQL', spec({ columns: [emptyColumn({ name: 'note', type: 'TEXT', params: '', defaultValue: 'none yet' })] }));
  assert.ok(pg.includes(`"note" TEXT DEFAULT 'none yet'`), 'PostgreSQL is unchanged');
});

test('type arguments are formatted', () => {
  assert.equal(columnTypeSql('POSTGRESQL', emptyColumn({ type: 'NUMERIC', params: '12, 4' })), 'NUMERIC(12,4)');
  assert.equal(columnTypeSql('POSTGRESQL', emptyColumn({ type: 'TEXT', params: '' })), 'TEXT');
  assert.equal(columnTypeSql('POSTGRESQL', emptyColumn({ type: 'TEXT', params: '', unsigned: true })), 'TEXT');
  assert.deepEqual(enumValues(`a, 'b, c', "d"`), ['a', 'b, c', 'd']);
});

test('validation catches invalid definitions', () => {
  const errors = (engine, patch) => validateTable(engine, spec(patch));
  assert.deepEqual(errors('POSTGRESQL', { name: '', columns: [] }), ['Enter a table name.', 'Add at least one column.']);
  assert.ok(
    errors('POSTGRESQL', { columns: [emptyColumn({ name: 'id', type: 'TEXT', params: '', autoIncrement: true })] })[0].includes('integer')
  );
  assert.ok(
    errors('MYSQL', { columns: [emptyColumn({ name: 'id', type: 'INT', params: '', autoIncrement: true })] })[0].includes('primary key or unique')
  );
  assert.ok(errors('MYSQL', { columns: [emptyColumn({ name: 'n', type: 'VARCHAR', params: '' })] })[0].includes('length'));
  assert.ok(
    errors('POSTGRESQL', {
      columns: [emptyColumn({ name: 'a' }), emptyColumn({ name: 'A' })],
    })[0].includes('more than once')
  );
  assert.ok(
    errors('POSTGRESQL', {
      columns: [emptyColumn({ name: 'user_id', type: 'BIGINT', params: '', notNull: true })],
      foreignKeys: [{ name: '', column: 'user_id', refTable: 'users', refColumn: 'id', onDelete: 'SET NULL', onUpdate: 'NO ACTION' }],
    })[0].includes('SET NULL')
  );
  assert.deepEqual(
    errors('POSTGRESQL', { columns: [emptyColumn({ name: 'id', type: 'BIGINT', params: '', primaryKey: true, autoIncrement: true })] }),
    []
  );
});
